"""Generate an A8 Gaussian directly, avoiding inherited RGB565 color steps.

The high-frequency, zero-mean spatial dither survives nearest-neighbor image
scaling and helps distribute the final RGB565 quantization transitions.
"""
from pathlib import Path
import math
import random

WIDTH, HEIGHT = 360, 150
SIGMA_X, SIGMA_Y, PEAK = 58.0, 22.0, 136.0
SIZE = 64
rng = random.Random(0x175C)
white = [[rng.random() - 0.5 for _ in range(SIZE)] for _ in range(SIZE)]
values = []
for y in range(HEIGHT):
    for x in range(WIDTH):
        dx = (x - (WIDTH - 1) / 2) / SIGMA_X
        dy = (y - (HEIGHT - 1) / 2) / SIGMA_Y
        alpha = PEAK * math.exp(-0.5 * (dx * dx + dy * dy))
        xx, yy = x % SIZE, y % SIZE
        neighbors = (white[yy][(xx-1) % SIZE] + white[yy][(xx+1) % SIZE]
                     + white[(yy-1) % SIZE][xx] + white[(yy+1) % SIZE][xx]) / 4
        noise = max(-0.5, min(0.5, white[yy][xx] - neighbors))
        # Fade noise into black so the outside stays clean, with no hard edge.
        alpha += noise * 12.0 * min(1.0, alpha / 12.0)
        values.append(max(0, min(255, round(alpha))))

lines = ['/* Generated by sim/generate_bloom.py: continuous Gaussian + spatial dither. */',
         '#include "lvgl.h"', '',
         f'#define INKORB_BLOOM_W {WIDTH}', f'#define INKORB_BLOOM_H {HEIGHT}', '',
         'static const uint8_t inkorb_time_bloom_map[] = {']
for start in range(0, len(values), 16):
    lines.append('    ' + ', '.join(f'0x{v:02X}' for v in values[start:start+16]) + ',')
lines += ['};', '', 'const lv_image_dsc_t inkorb_time_bloom_img = {',
          '    .header = {', '        .magic = LV_IMAGE_HEADER_MAGIC,',
          '        .cf = LV_COLOR_FORMAT_A8,', '        .w = INKORB_BLOOM_W,',
          '        .h = INKORB_BLOOM_H,', '        .stride = INKORB_BLOOM_W,',
          '    },', '    .data_size = sizeof(inkorb_time_bloom_map),',
          '    .data = inkorb_time_bloom_map,', '};', '']
target = Path(__file__).resolve().parents[1] / 'main/inkorb_time_bloom_img.c'
target.write_text('\n'.join(lines))
print(f'{target.name}: {WIDTH}x{HEIGHT}, {len(set(values))} alpha levels')
